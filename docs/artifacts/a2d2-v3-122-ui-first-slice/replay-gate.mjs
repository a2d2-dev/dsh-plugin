import { readFile, readdir } from 'node:fs/promises'
import assert from 'node:assert/strict'
const root = new URL('./', import.meta.url)
const json = async name => JSON.parse(await readFile(new URL(name, root), 'utf8'))
const ids = snapshot => snapshot.sessions.map(row => row.sessionId).sort()
const files = (await readdir(root)).filter(name => name.endsWith('-snapshot.json')).sort()
assert.equal(files.length, 3)
const [beforeBrowser, restored, beforeStart] = await Promise.all(files.map(json))
assert.deepEqual(ids(beforeBrowser), [])
assert.equal(restored.sessions.length, 1)
assert.equal(restored.sessions[0].eventTypes.includes('turn/start'), false)
const fixture = await json('1792470585139-fixture.json')
const fixtureIds = Object.values(fixture.sessions).map(row => row.sessionId)
const expected = [...ids(restored), ...fixtureIds].sort()
assert.equal(new Set(expected).size, 5)
assert.deepEqual(ids(beforeStart), expected)
const phase = await json('phase-no-execution-navigation.json')
const check = await json('1792470951941-check-no-execution-navigation.json')
assert.equal(check.passed, true)
assert.deepEqual(ids(phase), expected)
assert.deepEqual(check.before, phase)
assert.deepEqual(check.current, phase)
for (const snapshot of [beforeBrowser, restored, beforeStart, phase, check.current]) {
  assert.equal(snapshot.gateway, 0)
  assert.equal(snapshot.adapter, 0)
  assert.deepEqual(snapshot.defaultModel, { provider: 'acceptance-disabled', model: 'no-model' })
  assert.ok(snapshot.sessions.every(row => !row.eventTypes.includes('turn/start')))
}
const metrics = (await readFile(new URL('metrics.jsonl', root), 'utf8')).trim().split('\n').map(JSON.parse)
assert.deepEqual(metrics.filter(row => row.kind === 'session-born').map(row => row.sessionId).sort(), expected)
assert.equal(metrics.filter(row => ['gateway', 'adapter', 'authorized', 'prompt-submitted'].includes(row.kind)).length, 0)
const initial = await json('05-initial-public-work.json')
assert.equal(initial.execution.http, 200)
assert.equal(initial.execution.body.execution, undefined)
const associations = await json('07-public-associations.json')
assert.deepEqual(associations.rows.map(row => row.http), [200, 200])
assert.deepEqual(associations.rows.map(row => row.request.value.purpose), ['related', 'review'])
assert.equal(associations.execution.body.execution, undefined)
const start = await json('09-public-task-start.json')
assert.equal(start.start.http, 400)
assert.equal(start.start.body.error.code, 'host-admission-failed')
assert.equal(start.execution.http, 200)
assert.equal(start.execution.body.execution, undefined)
const retention = await json('11-list-retention.json')
assert.equal(retention.project, '122 首片真实执行验收')
assert.equal(retention.search, '122 首片')
assert.deepEqual(retention.selectedTabs, ['项目', '已关联会话'])
assert.equal(retention.currentButtons, 0)
const cleanup = await json('14-cleanup.json')
assert.equal(cleanup.passed, true)
assert.equal(cleanup.collectedExitCode, 0)
assert.equal(cleanup.portResult, 'ECONNREFUSED')
console.log(JSON.stringify({ observedSubsetPassed: true, productStartGate: 'blocked: host-admission-failed', sessionCounts: [0, 1, 5, 5], gateway: 0, adapter: 0, readyActualCurrentNavigation: 'not verified', cleanupPassed: true }, null, 2))
